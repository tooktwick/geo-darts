// カテゴリーごとの一般的なエピソードテンプレート
function generateDefaultEpisode(lm) {
  const cat = lm.category;
  if (cat === 'castle') {
    return `戦国の武将たちが知略を尽くして築き上げた要衝。城下町を見下ろす石垣や縄張りに往時の歴史ロマンが漂う。`;
  } else if (cat === 'shrine_temple') {
    return `古くから地域の人々の信仰を集め、厄除けや招福の祈りが捧げられてきた由緒ある神仏の杜。`;
  } else if (cat === 'nature') {
    return `悠久の歳月と厳しい風雪が削り出した奇跡の造形美。四季折々に表情を変える壮大な景観が人々を魅了する。`;
  } else if (cat === 'hotspring') {
    return `地底深くから絶え間なく湧き出る大地の恵み。古くから旅人や文人墨客の心身を癒やし続けてきた天下の名湯。`;
  } else if (cat === 'gourmet') {
    return `その土地の豊かな気候風土と伝統の職人技が育んだ自慢の郷土の味。訪れた旅人の舌を唸らせる絶品。`;
  } else if (cat === 'heritage') {
    return `先人たちの英知と祈りが刻まれた貴重な歴史遺産。時代の変遷を乗り越えて今日まで受け継がれてきた。`;
  } else if (cat === 'garden') {
    return `計算し尽くされた空間美と四季の花々が調和する名園。訪れる人々に静寂と癒やしのひとときをもたらす。`;
  } else {
    return `地域のランドマークとして愛され、多くの旅人が足を運ぶ人気スポット。街の活気と魅力を発信し続けている。`;
  }
}

// 読み込みとエンリッチ処理
console.log('Reading landmarksData.ts...');
const content = fs.readFileSync('src/data/landmarksData.ts', 'utf8');

// 都道府県ごとに分割
const sections = content.split(/\/\/\s*都道府県\s*(\d+)/);
let newOutput = sections[0]; // ヘッダー部

let enrichedCount = 0;

for (let i = 1; i < sections.length; i += 2) {
  const prefId = Number(sections[i]);
  const blockText = sections[i + 1];

  newOutput += `// 都道府県 ${prefId}\n`;

  // オブジェクトブロックを置換
  // { id: '...', ... fameLevel: '...' }
  const regex = /\{\s*id:\s*'([^']+)',\s*name:\s*'([^']+)',[\s\S]*?category:\s*'([^']+)',\s*fameLevel:\s*'([^']+)',?\s*\}/g;

  const updatedBlock = blockText.replace(regex, (fullMatch, id, name, category, fameLevel) => {
    enrichedCount++;
    const gourmet = SPECIFIC_GOURMET[id] || PREF_GOURMET[prefId] || 'ご当地の名産・郷土料理';
    const episode = SPECIFIC_EPISODES[id] || generateDefaultEpisode({ id, name, category });

    // description の後ろや fameLevel の後ろに localGourmet と episode を追加
    // インデントを考慮
    return fullMatch.replace(
      new RegExp(`fameLevel:\\s*'${fameLevel}',?`),
      `fameLevel: '${fameLevel}',\n    localGourmet: '${gourmet}',\n    episode: '${episode}',`
    );
  });

  newOutput += updatedBlock;
}

console.log('Enriched landmarks count:', enrichedCount);
if (enrichedCount !== 940) {
  console.error(`ERROR: Enriched count is ${enrichedCount} instead of 940!`);
  process.exit(1);
}

fs.writeFileSync('src/data/landmarksData.ts', newOutput, 'utf8');
console.log('SUCCESS: src/data/landmarksData.ts successfully enriched with localGourmet and episode!');
