/**
 * クイズマスターから重複なくランダムに指定数の問題を抽出する
 * @param count 抽出問題数 (デフォルト5問)
 */
export const getRandomQuizSet = (count: number = 5): GeoQuizQuestion[] => {
  const shuffled = [...GEO_QUIZ_QUESTIONS].sort(() => Math.random() - 0.5);
  return shuffled.slice(0, Math.min(count, shuffled.length));
};

/**
 * 問題IDからクイズデータを取得する
 */
export const getQuizQuestionById = (id: string): GeoQuizQuestion | undefined => {
  return GEO_QUIZ_QUESTIONS.find((q) => q.id === id);
};

